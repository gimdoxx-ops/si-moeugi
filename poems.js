/* ─────────────────────────────────────────────────────────────
   ▼ 여기부터 끝까지는 위의 시를 사이트가 읽을 수 있게 바꿔 주는 부분이에요.
     시를 고칠 때는 건드리지 않아도 돼요.
   ───────────────────────────────────────────────────────────── */
function 시(조각) {
  var 칸 = { "제목": "title", "시인": "author", "본문": "text", "주머니 속 한마디": "note", "한마디": "note" };
  var 글 = 조각.raw[0];
  for (var i = 1; i < arguments.length; i++) 글 += String(arguments[i]) + 조각.raw[i];
  var 모음 = {}, 지금 = null, 경고 = [];
  글.replace(/\r/g, "").split("\n").forEach(function (줄) {
    var m = 줄.match(/^\s*\[\s*([^\]]+?)\s*\]\s*(.*)$/);
    if (m && 칸[m[1]]) {
      지금 = 칸[m[1]];
      모음[지금] = 모음[지금] || [];
      if (m[2].trim()) 모음[지금].push(m[2]);
      return;
    }
    if (m) 경고.push("모르는 칸 이름이 있어요: [" + m[1] + "]");
    if (지금) 모음[지금].push(줄);
    else if (줄.trim()) 경고.push("칸 이름 없이 적힌 줄이 있어요: " + 줄.trim());
  });
  // 줄마다 앞뒤 띄어쓰기를 지우고, 맨 위·맨 아래 빈 줄을 정리해요
  function 다듬기(줄들) {
    var a = (줄들 || []).map(function (s) { return s.trim(); });
    while (a.length && !a[0]) a.shift();
    while (a.length && !a[a.length - 1]) a.pop();
    return a;
  }
  // 한마디에 < > & 를 써도 글자 그대로 보이게
  function 글자그대로(s) { return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }
  var 한마디 = 다듬기(모음.note).join("\n");
  var 편 = {
    title: 다듬기(모음.title).filter(Boolean).join(" "),
    author: 다듬기(모음.author).filter(Boolean).join(" "),
    text: 다듬기(모음.text).join("\n"),
    note: 한마디 ? 한마디.split(/\n\s*\n/).map(function (문단) {
      return 다듬기(문단.split("\n")).map(글자그대로).join("<br>");
    }) : []
  };
  if (경고.length) 편.warnings = 경고;   // preview.html이 빨간 글씨로 알려 줘요
  (시.목록 = 시.목록 || []).push(편);
}
const POEMS = 시.목록 || [];
